/**
 * 把 Next.js Standalone 运行所需内容暂存到 .desktop/runtime/。
 * 该目录是可再生构建产物，绝不包含 data/、.env* 或模型权重。
 */
import { access, copyFile, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const standalone = join(root, ".next", "standalone");
const staticAssets = join(root, ".next", "static");
const publicAssets = join(root, "public");
const migrations = join(root, "drizzle");
const desktopRoot = join(root, ".desktop");
const runtime = join(desktopRoot, "runtime");
const runtimeMarker = join(runtime, ".chordnote-desktop-runtime");

async function requirePath(path, label) {
  try {
    await access(path);
  } catch {
    throw new Error(`${label} 缺失：${path}。请先运行 pnpm build。`);
  }
}

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function cleanPreviousRuntime() {
  if (!(await exists(runtime))) return;

  if (!(await exists(runtimeMarker))) {
    throw new Error(`拒绝清理未标记的目录：${runtime}`);
  }

  await rm(runtime, { recursive: true, force: true });
}

await requirePath(join(standalone, "server.js"), "Next.js Standalone server.js");
await requirePath(staticAssets, "Next.js 静态资源");
await requirePath(migrations, "Drizzle 迁移目录");
await cleanPreviousRuntime();
await mkdir(desktopRoot, { recursive: true });

// dereference 必不可少：pnpm 的 node_modules 有链接，安装包不能依赖开发机的 store 路径。
await cp(standalone, runtime, { recursive: true, dereference: true, force: true });
await cp(staticAssets, join(runtime, ".next", "static"), { recursive: true, force: true });
if (await exists(publicAssets)) {
  await cp(publicAssets, join(runtime, "public"), { recursive: true, force: true });
}
await cp(migrations, join(runtime, "drizzle"), { recursive: true, force: true });

const nodeDestination = join(runtime, process.platform === "win32" ? "node.exe" : "node");
await copyFile(process.execPath, nodeDestination);
await requirePath(join(runtime, "node_modules", "@electric-sql", "pglite"), "PGlite 运行时依赖");

// 先在构建机验证已复制的 Node 可独立启动，避免把开发机路径带入包内。
await execFileAsync(nodeDestination, ["--version"], { windowsHide: true });
await writeFile(runtimeMarker, "Generated by scripts/prepare-desktop.mjs\n", "utf8");

const manifest = {
  generatedAt: new Date().toISOString(),
  nodeVersion: process.version,
  server: "server.js",
  staticAssets: ".next/static",
  migrations: "drizzle",
};
await writeFile(join(runtime, "runtime-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

// 读一次 marker，确保资源暂存完成后才返回成功。
await readFile(runtimeMarker, "utf8");
console.log(`Desktop runtime staged at ${runtime}`);
